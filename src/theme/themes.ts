export const DEFAULT_THEME_ID: ThemeId = "rt-dark"
export const THEME_IDS: ThemeId[] = Object.keys(THEMES) as ThemeId[]
export const THEME_GROUPS = ["builtin", "terminal", "community"] as const

export function resolveThemeId(storedValue: string | null | undefined): ThemeId {
  if (!storedValue) return DEFAULT_THEME_ID
  if (storedValue === "dark") return "rt-dark"
  if (storedValue === "light") return "rt-light"
  if (storedValue in THEMES) return storedValue as ThemeId
  return DEFAULT_THEME_ID
}

export function applyTheme(themeId: ThemeId): AppTheme {
  const resolved = resolveThemeId(themeId)
  const theme = THEMES[resolved] || THEMES[DEFAULT_THEME_ID]

  if (typeof document !== "undefined") {
    const root = document.documentElement
    root.setAttribute("data-theme", theme.id)

    // Set class for Tailwind darkMode and compatibility
    if (theme.type === "dark") {
      root.classList.add("dark")
      root.classList.remove("light")
    } else {
      root.classList.add("light")
      root.classList.remove("dark")
    }

    // Apply all CSS variables directly to root element
    for (const [key, value] of Object.entries(theme.cssVars)) {
      root.style.setProperty(key, value)
    }
  }

  return theme
}
